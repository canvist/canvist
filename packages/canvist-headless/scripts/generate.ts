/**
 * Generate the extension descriptors from the metadata that
 * `canvist_extensions` snapshots in its tests, so the TypeScript types come
 * from the same metadata the Rust commands are checked against:
 *
 * - `src/extensions.generated.ts`: the core and StarterKit extensions, which
 *   `@canvist/headless` compiles in;
 * - `src/extras.generated.ts`: every other extension, which only
 *   `@canvist/headless/full` compiles in;
 * - `src/gemoji.generated.ts`: the emoji table, which the full module loads
 *   on first use rather than compiling it in.
 *
 * Every extension comes from the full metadata snapshot; the StarterKit
 * snapshot says which of them make up `starterKit`, the default set.
 *
 * Descriptions become comments rather than data: types never read them,
 * and as data they would ship in every browser bundle. `engine.metadata()`
 * returns them from Rust.
 *
 * Run with `node scripts/generate.ts` or `deno run -R -W scripts/generate.ts`.
 * Pass `--check` to fail instead of writing when the file is out of date.
 *
 * @module
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const snapshots = "../../../crates/canvist_extensions/tests/snapshots/";
const everySnapshot = new URL(
	`${snapshots}extensions_api__extension_metadata.snap`,
	import.meta.url,
);
const starterKitSnapshot = new URL(
	`${snapshots}api__starter_kit_metadata.snap`,
	import.meta.url,
);
const gemoji = new URL(
	"../../../crates/extensions/emoji/src/gemoji.txt",
	import.meta.url,
);
const gemojiLicense = new URL(
	"../../../crates/extensions/emoji/src/gemoji-license.txt",
	import.meta.url,
);

/** Extensions every engine registers, so TypeScript lists them for you. */
const CORE = ["doc", "paragraph", "baseKeymap", "undoInputRule"];

interface Described {
	readonly name: string;
}

/** The JSON body of an insta snapshot: everything after its header. */
function snapshotBody(text: string): string {
	const header = /^---\n[\s\S]*?\n---\n/;
	return text.replace(header, "");
}

const HEADER =
	"// Generated by scripts/generate.ts from canvist_extensions' metadata snapshots. Do not edit.\n";

function declare(extension: Described): string {
	return `/** The \`${extension.name}\` extension. */\nexport const ${extension.name} = ${
		literal(extension, "")
	} as const satisfies ExtensionDescriptor;\n`;
}

function list(items: readonly Described[]): string {
	return items.map((item) => item.name).join(", ");
}

/** The two descriptor files: the StarterKit's, and every other extension's. */
function render(
	extensions: readonly Described[],
	starterKitNames: readonly string[],
): { readonly starterKit: string; readonly extras: string } {
	const core = extensions.filter((extension) => CORE.includes(extension.name));
	const named = (name: string) =>
		extensions.find((extension) => extension.name === name);
	const starterKit = starterKitNames
		.filter((name) => !CORE.includes(name))
		.map(named)
		.filter((extension) => extension !== undefined);
	const extras = extensions.filter((extension) =>
		!CORE.includes(extension.name) && !starterKitNames.includes(extension.name)
	);

	return {
		starterKit: [
			HEADER,
			'import type { ExtensionDescriptor } from "./types.ts";\n',
			...[...core, ...starterKit].map(declare),
			"/** The extensions every engine registers. */",
			`export const core = [${list(core)}] as const;\n`,
			"/** Every optional StarterKit extension, the default for `createEngine`. */",
			`export const starterKit = [${list(starterKit)}] as const;\n`,
		].join("\n"),
		extras: [
			HEADER,
			'import { starterKit } from "./extensions.generated.ts";',
			'import type { ExtensionDescriptor } from "./types.ts";\n',
			...extras.map(declare),
			"/** Every extension beyond the StarterKit, which `@canvist/headless/full` compiles in. */",
			`export const extras = [${list(extras)}] as const;\n`,
			"/** Every optional extension canvist ships, the StarterKit's included. */",
			`export const allExtensions = [...starterKit, ...extras] as const;\n`,
		].join("\n"),
	};
}

/** The emoji table as a module, with gemoji's licence. */
function renderGemoji(table: string, license: string): string {
	const comment = license.trimEnd().split("\n").map((line) =>
		line === "" ? " *" : ` * ${line}`
	);

	return [
		"// Generated by scripts/generate.ts from canvist_extensions' gemoji table. Do not edit.",
		"/**",
		" * GitHub's gemoji: one emoji per line, a tab, and its shortcodes.",
		" *",
		...comment,
		" *",
		" * @module",
		" */",
		`export const gemoji: string = ${JSON.stringify(table)};\n`,
	].join("\n");
}

/**
 * `value` as a tab-indented TypeScript literal, like `JSON.stringify`, with
 * each `doc` moved out of the data into a comment above its object.
 */
function literal(value: unknown, indent: string): string {
	const inner = `${indent}\t`;

	if (Array.isArray(value)) {
		if (value.length === 0) {
			return "[]";
		}

		const items = value.map((item) =>
			`${comment(item, inner)}${inner}${literal(item, inner)}`
		);
		return `[\n${items.join(",\n")}\n${indent}]`;
	}

	if (value !== null && typeof value === "object") {
		const entries = Object.entries(value).filter(([key]) => key !== "doc");

		if (entries.length === 0) {
			return "{}";
		}

		const fields = entries.map(([key, item]) =>
			`${inner}${JSON.stringify(key)}: ${literal(item, inner)}`
		);
		return `{\n${fields.join(",\n")}\n${indent}}`;
	}

	return JSON.stringify(value);
}

/** A JSDoc line holding `item`'s `doc`, or nothing when it has none. */
function comment(item: unknown, indent: string): string {
	const doc = item !== null && typeof item === "object" && "doc" in item
		? item.doc
		: undefined;

	return typeof doc === "string" ? `${indent}/** ${doc} */\n` : "";
}

function read(snapshot: URL): readonly Described[] {
	return JSON.parse(snapshotBody(readFileSync(snapshot, "utf8")));
}

const descriptors = render(
	read(everySnapshot),
	read(starterKitSnapshot).map((extension) => extension.name),
);
const outputs: ReadonlyMap<string, string> = new Map([
	["extensions.generated.ts", descriptors.starterKit],
	["extras.generated.ts", descriptors.extras],
	[
		"gemoji.generated.ts",
		renderGemoji(
			readFileSync(gemoji, "utf8"),
			readFileSync(gemojiLicense, "utf8"),
		),
	],
]);
const stale: string[] = [];

for (const [name, generated] of outputs) {
	const output = new URL(`../src/${name}`, import.meta.url);

	if (!process.argv.includes("--check")) {
		writeFileSync(output, generated);
	} else if (
		!existsSync(output) || readFileSync(output, "utf8") !== generated
	) {
		stale.push(`src/${name}`);
	}
}

if (stale.length > 0) {
	console.error(`${stale.join(", ")} out of date; run scripts/generate.ts`);
	process.exit(1);
}
